alter table members add column if not exists emergency_contact text;
alter table members add column if not exists registration_payment_proof_name text;
alter table members add column if not exists registration_payment_proof_url text;
alter table members add column if not exists agreed_terms boolean default false;

create table if not exists app_users (
  id bigint generated by default as identity primary key,
  member_id bigint references members(id) on delete set null,
  name text not null,
  email text not null unique,
  password text not null,
  role text not null default 'member',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint app_users_role_check check (role in ('admin', 'member'))
);

create table if not exists reload_requests (
  id bigint generated by default as identity primary key,
  member_id bigint not null references members(id) on delete restrict,
  member_name text,
  amount numeric(10, 2) not null,
  status text not null default 'Pending',
  date date not null default current_date,
  payment_screenshot text,
  screenshot_name text,
  screenshot_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint reload_requests_amount_check check (amount > 0),
  constraint reload_requests_status_check check (
    status in ('Pending', 'Approved', 'Rejected')
  )
);

create table if not exists transactions (
  id bigint generated by default as identity primary key,
  member_id bigint not null references members(id) on delete restrict,
  date date not null default current_date,
  description text not null,
  amount numeric(10, 2) not null,
  type text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint transactions_type_check check (
    type is null or type in (
      'reload',
      'session_charge',
      'manual_expense',
      'manual_adjustment',
      'other'
    )
  )
);

create table if not exists sessions (
  id bigint generated by default as identity primary key,
  date date not null,
  time text not null,
  venue text not null,
  court_count integer not null,
  max_players integer not null,
  court_fee_total numeric(10, 2) not null,
  cancel_cutoff time,
  walk_in_limit integer not null default 5,
  status text not null default 'open',
  charge_status text not null default 'not_charged',
  shuttlecock_used integer not null default 0,
  shuttlecock_rate numeric(10, 2) not null default 0,
  other_fee_total numeric(10, 2) not null default 0,
  charged_at timestamptz,
  finalized_court_charge_per_player numeric(10, 2),
  finalized_attended_charge_per_player numeric(10, 2),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint sessions_court_count_check check (court_count > 0),
  constraint sessions_max_players_check check (max_players > 0),
  constraint sessions_court_fee_total_check check (court_fee_total >= 0),
  constraint sessions_shuttlecock_used_check check (shuttlecock_used >= 0),
  constraint sessions_shuttlecock_rate_check check (shuttlecock_rate >= 0),
  constraint sessions_other_fee_total_check check (other_fee_total >= 0),
  constraint sessions_status_check check (status in ('open', 'closed')),
  constraint sessions_charge_status_check check (
    charge_status in ('not_charged', 'charged')
  )
);

create table if not exists session_bookings (
  id bigint generated by default as identity primary key,
  session_id bigint not null references sessions(id) on delete cascade,
  member_id bigint not null references members(id) on delete restrict,
  status text not null default 'booked',
  booked_at timestamptz not null default now(),
  cancelled_at timestamptz,
  status_updated_at timestamptz,
  walk_in_count integer not null default 0,
  walk_in_names text[] not null default '{}',
  member_attached_walkin_charge_mode text not null default 'collect_separately',
  late_cancelled_walk_in_count integer not null default 0,
  late_cancelled_walk_in_names text[] not null default '{}',
  waitlist_type text,
  waitlist_status text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint session_bookings_status_check check (
    status in ('booked', 'attended', 'no_show', 'late_cancel', 'cancelled')
  ),
  constraint session_bookings_member_attached_walkin_charge_mode_check check (
    member_attached_walkin_charge_mode in (
      'collect_separately',
      'deduct_walkin_fee',
      'charge_as_member'
    )
  )
);

