-- BYT Club Wallet Supabase/PostgreSQL schema
-- This schema uses bigint identity primary keys because the current prototype
-- stores numeric ids, including Date.now() values, in localStorage.

create or replace function update_updated_at_column()
returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;

create table if not exists members (
  id bigint generated by default as identity primary key,
  name text not null,
  email text unique,
  whatsapp text,
  balance numeric(10, 2) not null default 0,
  status text not null default 'active',
  member_type text,
  package_type text,
  package_name text,
  package_price numeric default 0,
  package_credit numeric default 0,
  registration_fee numeric default 0,
  gift_choice text,
  uniform_size text,
  gender text,
  birthday text,
  emergency_contact text,
  registration_payment_proof_name text,
  registration_payment_proof_url text,
  agreed_terms boolean default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint members_status_check check (status in ('active', 'inactive', 'pending')),
  constraint members_member_type_check check (
    member_type is null or member_type in ('new', 'regular', 'guest')
  )
);

